def l2_category_names(parent_l1):
    return list(L2_CATEGORY_PROFILES.get(parent_l1, {}).keys())


def l2_category_profile_text(parent_l1, l2_name):
    profile = L2_CATEGORY_PROFILES[parent_l1][l2_name]
    return (
        f"L1：{parent_l1}。"
        f"L2 類別：{l2_name}。"
        f"分類標準：{profile['description']}"
        f"例如：{profile['example']}"
        f"邊界：{profile['boundary']}"
    )


def l2_standard_text(parent_l1):
    profiles = L2_CATEGORY_PROFILES.get(parent_l1, {})
    if not profiles:
        return f"【{parent_l1}】目前尚未建立 Level 2 分類標準。"
    parts = [
        f"【{parent_l1}－Level 2 分類標準】",
        f"每題至少選 {L2_MIN_LABELS} 個、最多選 {L2_MAX_LABELS} 個 L2 類別。",
        "只在問題確實同時包含多個獨立知識面向時才多標；不可為了湊數而增加類別。",
        "L2 類別不要求題數平均，應依實際問題內容與專業規則判斷。",
    ]
    for i, (name, profile) in enumerate(profiles.items(), start=1):
        parts.append(
            f"{i}. {name}\n"
            f"{profile['description']}\n"
            f"例如：{profile['example']}\n"
            f"邊界：{profile['boundary']}"
        )
    return "\n\n".join(parts)


def validate_l2_taxonomy():
    missing_l1 = [
        name for name in CATEGORY_NAMES
        if name not in L2_CATEGORY_PROFILES or not L2_CATEGORY_PROFILES[name]
    ]
    if missing_l1:
        raise ValueError(f"以下 L1 尚未建立 L2：{missing_l1}")
    extra_l1 = [name for name in L2_CATEGORY_PROFILES if name not in CATEGORY_NAMES]
    if extra_l1:
        raise ValueError(f"L2 含未知 L1：{extra_l1}")
    seen = {}
    duplicates = []
    for parent, children in L2_CATEGORY_PROFILES.items():
        for child, profile in children.items():
            if child in seen:
                duplicates.append((child, seen[child], parent))
            else:
                seen[child] = parent
            for key in ("description", "example", "boundary"):
                if not str(profile.get(key, "")).strip():
                    raise ValueError(f"{parent} / {child} 缺少 {key}")
    if duplicates:
        raise ValueError(f"發現重複 L2 名稱：{duplicates}")
    return {
        "l1_count": len(CATEGORY_NAMES),
        "l2_count": sum(len(children) for children in L2_CATEGORY_PROFILES.values()),
        "l2_counts_by_l1": {
            parent: len(children)
            for parent, children in L2_CATEGORY_PROFILES.items()
        },
    }


L2_TAXONOMY_VALIDATION = validate_l2_taxonomy()
