def l3_standard_text(parent_l1, parent_l2):
    profiles = SELECTIVE_L3_CATEGORY_PROFILES.get((parent_l1, parent_l2), {})
    if not profiles:
        return (
            f"【{parent_l1} → {parent_l2}】不建立 Level 3。"
            "此節點視為終端 L2，應直接進行節點內 retrieval。"
        )
    parts = [
        f"【{parent_l1} → {parent_l2}－Level 3 分類標準】",
        f"每題至少選 {L3_MIN_LABELS} 個、最多選 {L3_MAX_LABELS} 個 L3 類別。",
        "只有問題確實同時包含兩個獨立 L3 知識面向時才多標；不可為了湊數增加標籤。",
        "L3 routing 必須以既有 L1、L2 已確定為前提，不得跨越父節點。",
    ]
    for i, (name, profile) in enumerate(profiles.items(), start=1):
        parts.append(
            f"{i}. {name}\n"
            f"{profile['description']}\n"
            f"例如：{profile['example']}\n"
            f"邊界：{profile['boundary']}"
        )
    return "\n\n".join(parts)


def validate_l3_taxonomy():
    errors = []
    for (parent_l1, parent_l2), children in SELECTIVE_L3_CATEGORY_PROFILES.items():
        if parent_l2 not in L2_CATEGORY_PROFILES.get(parent_l1, {}):
            errors.append(f"未知 L3 parent：{parent_l1} > {parent_l2}")
        if len(children) < 2:
            errors.append(f"{parent_l1} > {parent_l2} 的 L3 少於 2 類")
        seen = set()
        for name, profile in children.items():
            if name in seen:
                errors.append(f"{parent_l1} > {parent_l2} 重複 L3：{name}")
            seen.add(name)
            for key in ("description", "example", "boundary"):
                if not str(profile.get(key, "")).strip():
                    errors.append(f"{parent_l1} > {parent_l2} > {name} 缺少 {key}")
    if errors:
        raise ValueError("L3 taxonomy validation failed:\n" + "\n".join(errors))
    return {
        "selected_parent_count": len(SELECTIVE_L3_CATEGORY_PROFILES),
        "l3_count": sum(len(children) for children in SELECTIVE_L3_CATEGORY_PROFILES.values()),
        "l3_counts_by_parent": {
            f"{l1} > {l2}": len(children)
            for (l1, l2), children in SELECTIVE_L3_CATEGORY_PROFILES.items()
        },
    }


L3_TAXONOMY_VALIDATION = validate_l3_taxonomy()
